#!/usr/bin/env node
/**
 * Company-fork M1 listening smoke.
 *
 * Builds the Worker, boots `wrangler dev --local` (no Cloudflare account),
 * syncs curated sample catalog entries, then asserts anonymous
 * GET /api/v1/plugins returns the Market-compatible wire shape
 * (packages / meta / installMethods).
 *
 * Usage (repo root, after npm ci):
 *   node scripts/smoke-company-plugins-api.mjs
 *   npm run smoke:company-plugins-api
 *
 * Env:
 *   SMOKE_BASE_URL   default http://127.0.0.1:8787 (skip boot if already up)
 *   SMOKE_SKIP_BOOT  set to 1 to only curl an already-running origin
 *   SMOKE_PORT       default 8787
 *   SMOKE_TIMEOUT_MS default 300000
 */

import { spawn } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { setTimeout as delay } from 'node:timers/promises'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const webRoot = join(root, 'apps/web')
const distWorker = join(webRoot, 'dist/company_store')
const samplesDir = join(root, 'docs/examples/curated-reviewed')
const evidenceDir = join(root, 'docs/examples/smoke-evidence')
const persistDir = join(webRoot, '.wrangler/state')
const port = Number(process.env.SMOKE_PORT || 8787)
const baseUrl = (process.env.SMOKE_BASE_URL || `http://127.0.0.1:${port}`).replace(/\/$/, '')
const skipBoot = process.env.SMOKE_SKIP_BOOT === '1'
const timeoutMs = Number(process.env.SMOKE_TIMEOUT_MS || 300_000)

const SYNC_TOKEN = 'smoke-catalog-sync-token-that-is-at-least-32b'
const INSTALL_SECRET = 'smoke-install-client-hash-secret-32bytes-min'

function fail(message) {
  console.error(`smoke-company-plugins-api: FAIL — ${message}`)
  process.exitCode = 1
}

function ok(message) {
  console.log(`smoke-company-plugins-api: ${message}`)
}

function loadSampleEntries() {
  const files = [
    'anweat--dsh-restart.json',
    'jesse-njx--dsh-crosstalk.json',
    'awesome-dsh-plugin--dsh-find-plugin.json',
  ]
  return files.map((name) => {
    const raw = JSON.parse(readFileSync(join(samplesDir, name), 'utf8'))
    return {
      id: raw.id,
      name: raw.name,
      repository: raw.repository,
      category: raw.category,
      description: {
        en: raw.description.en,
        zh: raw.description.zh,
      },
      added: raw.added,
    }
  })
}

function ensureDevVars() {
  const path = join(webRoot, '.dev.vars')
  if (!existsSync(path)) {
    const body = [
      '# Generated by scripts/smoke-company-plugins-api.mjs (gitignored)',
      'GITHUB_TOKEN=',
      `INSTALL_CLIENT_HASH_SECRET=${INSTALL_SECRET}`,
      `CATALOG_SYNC_TOKEN=${SYNC_TOKEN}`,
      'GITHUB_OAUTH_CLIENT_ID=smoke-oauth-client-id',
      'GITHUB_OAUTH_CLIENT_SECRET=smoke-oauth-client-secret',
      '',
    ].join('\n')
    writeFileSync(path, body, 'utf8')
    ok(`wrote ${path}`)
  } else {
    ok(`reusing existing ${path}`)
  }
}

function run(command, args, options = {}) {
  return new Promise((resolvePromise, reject) => {
    const child = spawn(command, args, {
      stdio: ['ignore', 'pipe', 'pipe'],
      env: process.env,
      ...options,
    })
    let stdout = ''
    let stderr = ''
    child.stdout.on('data', (chunk) => {
      stdout += chunk
      process.stdout.write(chunk)
    })
    child.stderr.on('data', (chunk) => {
      stderr += chunk
      process.stderr.write(chunk)
    })
    child.on('error', reject)
    child.on('close', (code) => {
      if (code === 0) resolvePromise({ stdout, stderr })
      else reject(new Error(`${command} ${args.join(' ')} exited ${code}\n${stderr}`))
    })
  })
}

async function migrateLocal() {
  ok('applying local D1 migrations…')
  await run(
    'npx',
    [
      'wrangler',
      'd1',
      'migrations',
      'apply',
      'CATALOG_DB',
      '--local',
      '--persist-to',
      persistDir,
    ],
    { cwd: webRoot },
  )
}

async function buildWorker() {
  ok('building Worker + client assets…')
  await run('npm', ['run', 'build', '--workspace', '@dsh-1024store/web'], { cwd: root })
  const distVars = join(distWorker, '.dev.vars')
  copyFileSync(join(webRoot, '.dev.vars'), distVars)
  ok(`synced secrets → ${distVars}`)
}

async function waitForOrigin(url, deadline) {
  while (Date.now() < deadline) {
    try {
      const response = await fetch(`${url}/api/v1/health`, {
        headers: { Accept: 'application/json' },
      })
      if (response.status < 500) return
    } catch {
      // not ready
    }
    await delay(1000)
  }
  throw new Error(`Timed out waiting for ${url}/api/v1/health`)
}

function readDevVar(name) {
  const path = join(webRoot, '.dev.vars')
  if (!existsSync(path)) return null
  const line = readFileSync(path, 'utf8')
    .split('\n')
    .find((row) => row.startsWith(`${name}=`))
  return line ? line.slice(name.length + 1).trim() : null
}

async function syncCatalog(entries) {
  const token = readDevVar('CATALOG_SYNC_TOKEN') || SYNC_TOKEN
  const response = await fetch(`${baseUrl}/api/v1/catalog/sync`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
      'User-Agent': 'company-store-smoke',
    },
    body: JSON.stringify({ source: 'github_ci', entries }),
  })
  const text = await response.text()
  if (!response.ok) {
    throw new Error(`catalog sync HTTP ${response.status}: ${text.slice(0, 400)}`)
  }
  const body = JSON.parse(text)
  if (body.ok !== true) {
    throw new Error(`catalog sync not ok: ${text.slice(0, 400)}`)
  }
  ok(`catalog sync ok (total=${body.total})`)
}

function assertPluginsBody(body) {
  if (!Array.isArray(body.packages) || body.packages.length === 0) {
    throw new Error('packages missing or empty')
  }
  if (!body.meta || typeof body.meta !== 'object') {
    throw new Error('meta missing')
  }
  for (const key of ['total', 'catalogTotal', 'updated', 'generatedAt', 'revision', 'source']) {
    if (body.meta[key] === undefined || body.meta[key] === null) {
      throw new Error(`meta.${key} missing`)
    }
  }
  const first = body.packages[0]
  if (typeof first.id !== 'string' || !first.id.includes('/')) {
    throw new Error('package.id invalid')
  }
  if (first.installMethods !== undefined && !Array.isArray(first.installMethods)) {
    throw new Error('installMethods must be an array when present')
  }
  for (const field of ['name', 'owner', 'url', 'category']) {
    if (typeof first[field] !== 'string' || first[field].length === 0) {
      throw new Error(`package.${field} missing`)
    }
  }
}

async function fetchPlugins() {
  const response = await fetch(`${baseUrl}/api/v1/plugins?limit=5`, {
    headers: { Accept: 'application/json' },
  })
  const text = await response.text()
  if (!response.ok) {
    throw new Error(`GET /api/v1/plugins HTTP ${response.status}: ${text.slice(0, 400)}`)
  }
  const body = JSON.parse(text)
  assertPluginsBody(body)
  return { response, body, text }
}

function writeEvidence({ body, text }) {
  mkdirSync(evidenceDir, { recursive: true })
  const stamp = new Date().toISOString().replace(/[:.]/g, '-')
  const fileName = `plugins-api-${stamp}.json`
  const jsonPath = join(evidenceDir, fileName)
  const summaryPath = join(evidenceDir, 'LATEST.md')
  writeFileSync(jsonPath, `${JSON.stringify(body, null, 2)}\n`, 'utf8')
  const digest = createHash('sha256').update(text).digest('hex').slice(0, 16)
  const summary = [
    '# Company Store M1 smoke evidence (local listening origin)',
    '',
    `Captured: ${new Date().toISOString()}`,
    `Origin: \`${baseUrl}\``,
    `Runtime: \`wrangler dev --local\` (no Cloudflare account)`,
    `Request: \`GET ${baseUrl}/api/v1/plugins?limit=5\``,
    `packages: ${body.packages.length}`,
    `meta.total: ${body.meta.total}`,
    `meta.source: ${body.meta.source}`,
    `meta.revision: ${body.meta.revision}`,
    `body sha256[0:16]: \`${digest}\``,
    `Artifact: [\`${fileName}\`](./${fileName})`,
    '',
    'Acceptance:',
    '- [x] Anonymous GET (no Authorization header)',
    '- [x] JSON includes `packages` and `meta`',
    '- [x] Package rows expose Market identity fields; `installMethods` array-or-absent',
    '',
    'Public HTTPS deploy still blocked without Cloudflare account + real domain',
    '(see `docs/company-fork-deploy.md` missing-credentials section).',
    '',
  ].join('\n')
  writeFileSync(summaryPath, summary, 'utf8')
  ok(`wrote evidence ${summaryPath}`)
}

async function main() {
  const deadline = Date.now() + timeoutMs
  const entries = loadSampleEntries()
  ok(`loaded ${entries.length} curated sample entries`)

  let child = null
  try {
    if (!skipBoot) {
      ensureDevVars()
      await migrateLocal()
      await buildWorker()
      const configPath = join(distWorker, 'wrangler.json')
      if (!existsSync(configPath)) {
        throw new Error(`missing built config ${configPath}`)
      }
      ok(`starting wrangler --local on ${baseUrl}…`)
      child = spawn(
        'npx',
        [
          'wrangler',
          'dev',
          '--local',
          '--ip',
          '127.0.0.1',
          '--port',
          String(port),
          '--persist-to',
          persistDir,
          '-c',
          configPath,
        ],
        {
          cwd: webRoot,
          stdio: ['ignore', 'pipe', 'pipe'],
          env: process.env,
          detached: true,
        },
      )
      child.stdout.on('data', (chunk) => process.stdout.write(chunk))
      child.stderr.on('data', (chunk) => process.stderr.write(chunk))
      child.on('exit', (code, signal) => {
        if ((process.exitCode === undefined || process.exitCode === 0) && code && code !== 0) {
          fail(`wrangler exited ${code} signal=${signal}`)
        }
      })
    }

    await waitForOrigin(baseUrl, deadline)
    ok(`origin ready: ${baseUrl}`)
    await syncCatalog(entries)
    const result = await fetchPlugins()
    writeEvidence(result)
    ok(
      `PASS — packages=${result.body.packages.length} meta.total=${result.body.meta.total} revision=${result.body.meta.revision}`,
    )
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error))
  } finally {
    if (child && child.pid) {
      try {
        process.kill(-child.pid, 'SIGTERM')
      } catch {
        try {
          child.kill('SIGTERM')
        } catch {
          // already gone
        }
      }
      await delay(1000)
      try {
        process.kill(-child.pid, 'SIGKILL')
      } catch {
        try {
          child.kill('SIGKILL')
        } catch {
          // already gone
        }
      }
    }
  }
}

await main()
